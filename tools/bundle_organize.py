#!/usr/bin/env python3
"""Generate td_organize/td_runtime.py = layout + overlap + td_adapter in one file.

    python tools/bundle_organize.py          # write
    python tools/bundle_organize.py --check  # exit 1 if stale
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PKG = ROOT / "td_organize"
PARTS = ["layout.py", "overlap.py", "td_adapter.py"]
OUT = PKG / "td_runtime.py"

HEADER = '''"""GENERATED by tools/bundle_organize.py -- do not edit.

Self-contained td-organize runtime for use inside TouchDesigner:

    exec(open('<path>/td_organize/td_runtime.py').read())
    organize(op('/project1/foo'))   # lay out
    check(op('/project1/foo'))      # list overlaps
"""
'''
FOOTER = '''

# exec() with separate globals/locals would hide helpers from the functions above.
globals().update({k: v for k, v in list(locals().items()) if not k.startswith("__")})
'''


def build():
    chunks = [HEADER]
    for name in PARTS:
        src = (PKG / name).read_text()
        src = re.sub(r'^""".*?"""\n', "", src, count=1, flags=re.S)
        src = re.sub(r"^from \.\w+ import .*\n", "", src, flags=re.M)
        chunks.append("# ---- %s ----\n%s" % (name, src.strip("\n") + "\n"))
    return "\n\n".join(chunks) + FOOTER


if __name__ == "__main__":
    text = build()
    if "--check" in sys.argv:
        ok = OUT.exists() and OUT.read_text() == text
        print("up to date" if ok else "STALE: run tools/bundle_organize.py")
        sys.exit(0 if ok else 1)
    OUT.write_text(text)
    print("wrote", OUT)
